/*
Урок 3.2 "Циклы", шаг 10

В гипотезе Коллатца число меняют так. Если оно чётное, его делят на 2, иначе умножают на 3 и
прибавляют 1. Считайте натуральное число и с помощью `while` выведите в одну строку через пробел всю
последовательность до 1.

Ввод и вывод. Входные данные читайте функцией `prompt()`. Каждый вызов возвращает следующую строку
ввода так же, как `prompt()` в браузере возвращает то, что ввёл пользователь. Результат выводите
через `console.log()`.

Пример ввода:

    6

Пример вывода:

    6 3 10 5 16 8 4 2 1
*/

// Скрытая часть кода на Stepik перед решением, её писать не нужно
const __input = require("fs").readFileSync(0, "utf8").replace(/\r/g, "").split("\n");
let __line = 0;
function prompt() { return __line < __input.length ? __input[__line++] : null; }


// Решение
let n = Number(prompt());
const steps = [n];
while (n !== 1) {
  n = n % 2 === 0 ? n / 2 : 3 * n + 1;
  steps.push(n);
}
console.log(steps.join(" "));
