/*
Урок 3.4 "Объекты", шаг 8

Дано меню кафе `const menu = { чай: 120, кофе: 180, торт: 250, сок: 150 };`. Считайте заказ,
названия блюд через пробел. Блюда могут повторяться, и в заказе могут быть блюда не из меню.
Выведите сумму заказа, а на следующей строке блюда не из меню через запятую с пробелом или `все
блюда есть в меню`.

Ввод и вывод. Входные данные читайте функцией `prompt()`. Каждый вызов возвращает следующую строку
ввода так же, как `prompt()` в браузере возвращает то, что ввёл пользователь. Результат выводите
через `console.log()`.

Пример ввода:

    чай торт

Пример вывода:

    370
    все блюда есть в меню
*/

// Скрытая часть кода на Stepik перед решением, её писать не нужно
const __input = require("fs").readFileSync(0, "utf8").replace(/\r/g, "").split("\n");
let __line = 0;
function prompt() { return __line < __input.length ? __input[__line++] : null; }


// Решение
const menu = { чай: 120, кофе: 180, торт: 250, сок: 150 };
let sum = 0;
const missing = [];
for (const item of prompt().split(" ")) {
  if (item in menu) {
    sum += menu[item];
  } else {
    missing.push(item);
  }
}
console.log(sum);
console.log(missing.length > 0 ? missing.join(", ") : "все блюда есть в меню");
