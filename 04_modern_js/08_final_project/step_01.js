// Скрытая часть кода на Stepik перед решением, её писать не нужно
const __input = require("fs").readFileSync(0, "utf8").replace(/\r/g, "").split("\n");
let __line = 0;
function prompt() { return __line < __input.length ? __input[__line++] : null; }


// Решение
function validate({ login, email, password, age }) {
  const errors = [];
  if (!/^\w{3,16}$/.test(login)) {
    errors.push("login: от 3 до 16 латинских букв, цифр или _");
  }
  const parts = email.split("@");
  if (email.includes(" ") || parts.length !== 2 || parts[0] === "" || !parts[1].includes(".")) {
    errors.push("email: неправильный адрес");
  }
  if (password.length < 8 || !/\d/.test(password)) {
    errors.push("password: минимум 8 символов и хотя бы одна цифра");
  }
  if (age !== undefined && !(Number.isInteger(age) && age >= 14 && age <= 100)) {
    errors.push("age: от 14 до 100");
  }
  return errors;
}

try {
  const errors = validate(JSON.parse(prompt()));
  console.log(errors.length > 0 ? errors.join("\n") : "Данные в порядке");
} catch (error) {
  console.log("Ошибка: неправильные данные");
}
