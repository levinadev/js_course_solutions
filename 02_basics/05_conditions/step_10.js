/*
Урок 2.5 "Условия", шаг 10

Считайте название сигнала светофора (`красный`, `жёлтый` или `зелёный`) и с помощью `switch`
выведите действие `стоп`, `внимание` или `идите`. Для любого другого ввода выведите `неизвестный
сигнал`.

Ввод и вывод. Входные данные читайте функцией `prompt()`. Каждый вызов возвращает следующую строку
ввода так же, как `prompt()` в браузере возвращает то, что ввёл пользователь. Результат выводите
через `console.log()`.

Пример ввода:

    красный

Пример вывода:

    стоп
*/

// Скрытая часть кода на Stepik перед решением, её писать не нужно
const __input = require("fs").readFileSync(0, "utf8").replace(/\r/g, "").split("\n");
let __line = 0;
function prompt() { return __line < __input.length ? __input[__line++] : null; }


// Решение
const signal = prompt();
switch (signal) {
  case "красный":
    console.log("стоп");
    break;
  case "жёлтый":
    console.log("внимание");
    break;
  case "зелёный":
    console.log("идите");
    break;
  default:
    console.log("неизвестный сигнал");
}
