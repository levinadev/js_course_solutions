/*
Урок 2.8 "Итоговый проект", шаг 1

Компания друзей ужинает в кафе и хочет разделить счёт поровну, добавив чаевые. Напишите калькулятор,
который это посчитает.

Ввод. Три строки.

- сумма счёта в рублях (может быть дробной);
- чаевые в процентах (целое число);
- количество человек (целое число).

Вывод. Три строки, суммы с двумя знаками после точки. Например, для счёта 3000, чаевых 15% и 4
человек ответ такой.

    Чаевые: 450.00 руб.
    Итого: 3450.00 руб.
    С каждого: 862.50 руб.

Проверки. Если сумма счёта не положительное число, выведите `Некорректная сумма`. Если количество
человек меньше 1 или не целое, выведите `Некорректное число гостей`. Проверяйте в этом порядке и
после первой ошибки больше ничего не выводите.

Чаевые считайте функцией `calcTip(total, tipPercent)`, которая возвращает сумму чаевых. Остальное
можно посчитать в основной программе.

Источники: MDN: Number.prototype.toFixed(); MDN: Number.isInteger().

Ввод и вывод. Входные данные читайте функцией `prompt()`. Каждый вызов возвращает следующую строку
ввода так же, как `prompt()` в браузере возвращает то, что ввёл пользователь. Результат выводите
через `console.log()`.

Пример ввода:

    3000
    15
    4

Пример вывода:

    Чаевые: 450.00 руб.
    Итого: 3450.00 руб.
    С каждого: 862.50 руб.
*/

// Скрытая часть кода на Stepik перед решением, её писать не нужно
const __input = require("fs").readFileSync(0, "utf8").replace(/\r/g, "").split("\n");
let __line = 0;
function prompt() { return __line < __input.length ? __input[__line++] : null; }


// Решение
function calcTip(total, tipPercent) {
  return total * tipPercent / 100;
}

const total = Number(prompt());
const tipPercent = Number(prompt());
const people = Number(prompt());

if (!(total > 0)) {
  console.log("Некорректная сумма");
} else if (!Number.isInteger(people) || people < 1) {
  console.log("Некорректное число гостей");
} else {
  const tip = calcTip(total, tipPercent);
  const sum = total + tip;
  console.log(`Чаевые: ${tip.toFixed(2)} руб.`);
  console.log(`Итого: ${sum.toFixed(2)} руб.`);
  console.log(`С каждого: ${(sum / people).toFixed(2)} руб.`);
}
