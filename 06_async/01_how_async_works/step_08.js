/*
Урок 6.1 "Как работает асинхронность", шаг 8

Считайте строку загрузок через пробел, каждая вида `файл:задержка`, например `a.txt:30 b.txt:10`.
Для каждой загрузки запустите `setTimeout` с её задержкой в миллисекундах. Таймер выводит `Загружен
ФАЙЛ`. Сразу после запуска всех таймеров выведите `Загрузка начата`.

Ввод и вывод. Входные данные читайте функцией `prompt()`. Каждый вызов возвращает следующую строку
ввода так же, как `prompt()` в браузере возвращает то, что ввёл пользователь. Результат выводите
через `console.log()`.

Пример ввода:

    a.txt:30 b.txt:10

Пример вывода:

    Загрузка начата
    Загружен b.txt
    Загружен a.txt
*/

// Скрытая часть кода на Stepik перед решением, её писать не нужно
const __input = require("fs").readFileSync(0, "utf8").replace(/\r/g, "").split("\n");
let __line = 0;
function prompt() { return __line < __input.length ? __input[__line++] : null; }


// Решение
for (const job of prompt().split(" ")) {
  const [file, ms] = job.split(":");
  setTimeout(() => console.log(`Загружен ${file}`), Number(ms));
}
console.log("Загрузка начата");
