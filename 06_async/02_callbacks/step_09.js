// Скрытая часть кода на Stepik перед решением, её писать не нужно
const __input = require("fs").readFileSync(0, "utf8").replace(/\r/g, "").split("\n");
let __line = 0;
function prompt() { return __line < __input.length ? __input[__line++] : null; }


// Решение
function step(name, ms, callback) {
  setTimeout(() => {
    console.log(`Готово: ${name}`);
    callback();
  }, ms);
}

const steps = prompt().split(" ").map((s) => s.split(":"));

step(steps[0][0], Number(steps[0][1]), () => {
  step(steps[1][0], Number(steps[1][1]), () => {
    step(steps[2][0], Number(steps[2][1]), () => {
      console.log("Ужин готов");
    });
  });
});
console.log("Начали");
